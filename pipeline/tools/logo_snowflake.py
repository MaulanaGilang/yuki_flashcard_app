"""Yuki logo: a flat 2D snowflake (雪, "yuki") on the Persimmon field.

One geometry, three outputs, so the launcher icon and the design files never drift:
  - android/app/src/main/res/drawable/ic_launcher_foreground.xml  (adaptive-icon vector)
  - design/logo/yuki-logo.svg
  - design/logo/yuki-logo-512.png (README, rendered with Pillow at 4x then downsampled)

Coordinates are in the 108-unit adaptive-icon viewport; everything stays inside the 66-unit
safe circle so OEM masks (ColorOS squircle on the Reno4) never clip an arm.

    python pipeline/tools/logo_snowflake.py
"""

from __future__ import annotations

import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]

FIELD = "#D63A22"   # Persimmon (DESIGN-SYSTEM §2.1)
SHADOW = "#A82A16"  # Persimmon, one step down: the sticker-style drop under the flake
SNOW = "#FFF8F3"    # warm white, same as the card paper

C = 54.0            # centre of the 108 viewport
ARM = 27.0          # arm length
STROKE = 4.6
BRANCH_AT = (10.5, 18.5)  # distance of the two branch pairs along each arm
BRANCH_LEN = (8.5, 6.0)
DROP = 2.2          # shadow offset, straight down


def segments() -> list[tuple[float, float, float, float]]:
  segs = []
  for k in range(6):
    a = math.radians(-90 + 60 * k)
    ex, ey = C + ARM * math.cos(a), C + ARM * math.sin(a)
    segs.append((C, C, ex, ey))
    for at, ln in zip(BRANCH_AT, BRANCH_LEN):
      bx, by = C + at * math.cos(a), C + at * math.sin(a)
      for side in (-1, 1):
        b = a + side * math.radians(50)
        segs.append((bx, by, bx + ln * math.cos(b), by + ln * math.sin(b)))
  return segs


def path_data(dy: float = 0.0) -> str:
  return " ".join(f"M{x1:.2f},{y1 + dy:.2f}L{x2:.2f},{y2 + dy:.2f}" for x1, y1, x2, y2 in segments())


def android_vector() -> str:
  return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Yuki logo foreground: flat snowflake with a sticker drop. Generated by pipeline/tools/logo_snowflake.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:strokeColor="{SHADOW}" android:strokeWidth="{STROKE}" android:strokeLineCap="round"
        android:strokeLineJoin="round" android:pathData="{path_data(DROP)}" />
    <path android:strokeColor="{SNOW}" android:strokeWidth="{STROKE}" android:strokeLineCap="round"
        android:strokeLineJoin="round" android:pathData="{path_data()}" />
    <path android:fillColor="{FIELD}" android:pathData="M{C - 2.6:.2f},{C:.2f}a2.6,2.6 0 1,0 5.2,0a2.6,2.6 0 1,0 -5.2,0z" />
</vector>
"""


def notification_icon() -> str:
  """Status-bar icon: the flake alone, white (Android tints it), cropped to its bounds."""
  return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Notification icon: Yuki snowflake. Generated by pipeline/tools/logo_snowflake.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="64"
    android:viewportHeight="64">
    <group android:translateX="-22" android:translateY="-22">
        <path android:strokeColor="#FFFFFFFF" android:strokeWidth="{STROKE}" android:strokeLineCap="round"
            android:strokeLineJoin="round" android:pathData="{path_data()}" />
    </group>
</vector>
"""


def svg() -> str:
  return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="512" height="512">
  <rect width="108" height="108" rx="24" fill="{FIELD}"/>
  <g fill="none" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round">
    <path stroke="{SHADOW}" d="{path_data(DROP)}"/>
    <path stroke="{SNOW}" d="{path_data()}"/>
  </g>
  <circle cx="{C}" cy="{C}" r="2.6" fill="{FIELD}"/>
</svg>
"""


def png(size: int = 512) -> Image.Image:
  ss = 4
  s = size * ss / 108
  img = Image.new("RGBA", (size * ss, size * ss), (0, 0, 0, 0))
  d = ImageDraw.Draw(img)
  d.rounded_rectangle([0, 0, size * ss - 1, size * ss - 1], radius=int(24 * s), fill=FIELD)
  w = STROKE * s
  for colour, dy in ((SHADOW, DROP), (SNOW, 0.0)):
    for x1, y1, x2, y2 in segments():
      p1, p2 = (x1 * s, (y1 + dy) * s), (x2 * s, (y2 + dy) * s)
      d.line([p1, p2], fill=colour, width=round(w))
      for px, py in (p1, p2):
        d.ellipse([px - w / 2, py - w / 2, px + w / 2, py + w / 2], fill=colour)
  r = 2.6 * s
  d.ellipse([C * s - r, C * s - r, C * s + r, C * s + r], fill=FIELD)
  return img.resize((size, size), Image.LANCZOS)


def main() -> None:
  res = ROOT / "android/app/src/main/res"
  (res / "drawable/ic_launcher_foreground.xml").write_text(android_vector(), encoding="utf-8")
  (res / "drawable/ic_stat_yuki.xml").write_text(notification_icon(), encoding="utf-8")
  logo = ROOT / "design/logo"
  logo.mkdir(parents=True, exist_ok=True)
  (logo / "yuki-logo.svg").write_text(svg(), encoding="utf-8")
  png().save(logo / "yuki-logo-512.png")
  print("wrote launcher vector, svg and 512 png")


if __name__ == "__main__":
  main()
